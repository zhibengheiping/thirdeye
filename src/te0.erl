-module(te0).

-export(
   [th1/1, prove_th1/1]).

tze() ->
    [term, '0'].

tpl([term, T], [term, R]) ->
    [term, [T, '+', R]].

a1([term, T], [term, R], [term, S]) ->
    ['⊦', [[T, '=', R],
           '→',
           [[T, '=', S],
            '→', [R, '=', S]]]].

a2([term, T]) ->
    ['⊦', [[T, '+', '0'], '=', T]].

mp(['⊦', P], ['⊦', [P, '→', Q]]) ->
    ['⊦', Q].

th1([term, T]) ->
    ['⊦', [T, '=', T]].

prove_th1(P1 = [term, T]) ->
    P2 = tze(),
    P2 = [term, '0'],

    P3 = tpl(P1, P2),
    P3 = [term, [T, '+', '0']],

    P4 = a1(P3, P1, P1),
    P4 = ['⊦', [[[T, '+', '0'], '=', T],
                '→',
                [[[T, '+', '0'], '=', T],
                 '→',
                 [T, '=', T]]]],

    P5 = a2(P1),
    P5 = ['⊦', [[T, '+', '0'], '=', T]],

    P6 = mp(P5, P4),
    P6 = ['⊦', [[[T, '+', '0'], '=', T],
                '→',
                [T, '=', T]]],

    P7 = mp(P5, P6),
    P7 = ['⊦', [T, '=', T]],

    P7.
