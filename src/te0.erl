-module(te0).

-export(
   [th1/1, prove_th1/1]).

-import(te, [mp/2]).

a1(T, R, S) ->
    ['⊦', [[T, '=', R],
           '→',
           [[T, '=', S],
            '→', [R, '=', S]]]].

a2(T) ->
    ['⊦', [[T, '+', '0'], '=', T]].

th1(T) ->
    ['⊦', [T, '=', T]].

prove_th1(T) ->
    P1 = a1([T, '+', '0'], T, T),
    P1 = ['⊦', [[[T, '+', '0'], '=', T],
                '→',
                [[[T, '+', '0'], '=', T],
                 '→',
                 [T, '=', T]]]],

    P2 = a2(T),
    P2 = ['⊦', [[T, '+', '0'], '=', T]],

    P3 = mp(P1, P2),
    P3 = ['⊦', [[[T, '+', '0'], '=', T],
                '→',
                [T, '=', T]]],

    P4 = mp(P3, P2),
    P4 = ['⊦', [T, '=', T]],

    P4.
