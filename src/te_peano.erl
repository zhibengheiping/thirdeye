-module(te_peano).

-export(
   ['0+0=0'/0, 'prove_0+0=0'/0]).

-import(te, [mp/2]).

'I'(X) ->
    ['⊦', [X, [X, 'I'], '=']].

'K'(X, Y) ->
    ['⊦', [X, [Y, X, 'K'], '=']].

'B'(F, G, X) ->
    ['⊦', [[[X|G]|F], [X, G, F, 'B'], '=']].

'C'(F, X, Y) ->
    ['⊦', [[X, Y|F], [Y, X, F, 'C'], '=']].

'Φ'(F, G, H, X) ->
    ['⊦', [[[X|H], [X|G]|F], [X, H, G, F, 'Φ'], '=']].

eq_comm(P, Q) ->
    ['⊦', [[P, Q, '='], [Q, P, '='], '→']].

eq_trans(P, Q, R) ->
    ['⊦', [[[R, P, '='], [R, Q, '='], '→'], [Q, P, '='], '→']].

iff(P, Q) ->
    ['⊦', [[[Q, P, '='], [P, Q, '→'], '→'], [Q, P, '→'], '→']].

iff_left(P, Q) ->
    ['⊦', [[Q, P, '→'], [Q, P, '='], '→']].

iff_right(P, Q) ->
    ['⊦', [[P, Q, '→'], [Q, P, '='], '→']].

forall_inst(P, X) ->
    ['⊦', [[X|P], [P, '∀'], '→']].

natp_0() ->
    ['⊦', ['0', natp]].

plus_0() ->
    ['⊦', [[[['I'], ['0', '+'], ['='], 'Φ'], [natp], ['→'], 'Φ'], '∀']].

nat_ind(P) ->
    ['⊦', [['0'|P],
           '→',
           [[[[[[succ], P, 'B'], P, ['→'], 'Φ'], [natp], ['→'], 'Φ'], '∀'],
            '→',
            [[P, [natp], ['→'], 'Φ'], '∀']]]].

'0+0=0'() ->
    ['⊦', ['0', ['0', '0', '+'], '=']].

'prove_0+0=0'() ->
    P1 = forall_inst([[['I'], ['0', '+'], ['='], 'Φ'], [natp], ['→'], 'Φ'], '0'),
    P2 = plus_0(),
    P3 = mp(P1, P2),
    P4 = iff_left(['0', [['I'], ['0', '+'], ['='], 'Φ'], [natp], ['→'], 'Φ'], [['0', ['I'], ['0', '+'], ['='], 'Φ'], ['0', natp], '→']),
    P5 = 'Φ'(['→'], [natp], [['I'], ['0', '+'], ['='], 'Φ'], '0'),
    P6 = mp(P4, P5),
    P7 = mp(P6, P3),
    P8 = natp_0(),
    P9 = mp(P7, P8),
    P10 = iff_left(['0', ['I'], ['0', '+'], ['='], 'Φ'], [['0', 'I'], ['0', '0', '+'],'=']),
    P11 = 'Φ'(['='], ['0', '+'], ['I'], '0'),
    P12 = mp(P10, P11),
    P13 = mp(P12, P9),
    P14 = 'I'('0'),
    P15 = eq_trans(['0', '0', '+'], ['0', 'I'], '0'),
    P16 = mp(P15, P13),
    P17 = mp(P16, P14),
    P17.
